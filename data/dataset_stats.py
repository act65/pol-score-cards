"""Compute summary statistics for the scraped article datasets.

Each dataset is a JSON file holding a list of article dicts with (at least)
headline / date / author / content / url. This scans a set of such files and
emits a Markdown report — article counts, date coverage, author counts, and
content-length distribution per source plus an aggregate.

Stdlib only; no API key or network needed.

    python dataset_stats.py                       # scans ./ and ./data for *.json
    python dataset_stats.py a.json data/b.json     # explicit files
    python dataset_stats.py --out DATASET_STATS.md
"""

import glob
import json
import os
import re
import statistics
import sys

DATE_RE = re.compile(r"(\d{4})-(\d{2})-(\d{2})")


def _date_key(value):
    """Return YYYY-MM-DD if a date is present in the string, else None."""
    if not value:
        return None
    m = DATE_RE.search(str(value))
    return f"{m.group(1)}-{m.group(2)}-{m.group(3)}" if m else None


def summarise(path):
    with open(path) as f:
        articles = json.load(f)
    if not isinstance(articles, list):
        return None

    n = len(articles)
    dates = [d for d in (_date_key(a.get("date")) for a in articles) if d]
    authors = [(a.get("author") or "").strip() for a in articles if (a.get("author") or "").strip()]
    lengths = [len(a.get("content", "") or "") for a in articles]
    word_counts = [len((a.get("content", "") or "").split()) for a in articles]

    return {
        "source": os.path.basename(path),
        "n_articles": n,
        "n_with_date": len(dates),
        "date_min": min(dates) if dates else None,
        "date_max": max(dates) if dates else None,
        "n_unique_authors": len(set(authors)),
        "n_missing_author": n - len(authors),
        "n_empty_content": sum(1 for l in lengths if l == 0),
        "median_chars": int(statistics.median(lengths)) if lengths else 0,
        "median_words": int(statistics.median(word_counts)) if word_counts else 0,
        "total_words": sum(word_counts),
    }


def discover():
    files = sorted(set(glob.glob("*.json") + glob.glob("data/*.json")))
    return files


def render(rows):
    lines = ["# Dataset statistics", ""]
    lines.append("Generated by `dataset_stats.py`. One row per scraped source file.")
    lines.append("")
    header = (
        "| Source | Articles | With date | Date range | Authors | Missing author | "
        "Empty content | Median words | Total words |"
    )
    sep = "|" + "---|" * 9
    lines += [header, sep]
    tot_articles = tot_words = 0
    for r in rows:
        if r is None:
            continue
        date_range = f"{r['date_min']} → {r['date_max']}" if r["date_min"] else "—"
        lines.append(
            f"| {r['source']} | {r['n_articles']} | {r['n_with_date']} | {date_range} | "
            f"{r['n_unique_authors']} | {r['n_missing_author']} | {r['n_empty_content']} | "
            f"{r['median_words']} | {r['total_words']:,} |"
        )
        tot_articles += r["n_articles"]
        tot_words += r["total_words"]
    lines.append(f"| **Total** | **{tot_articles}** | | | | | | | **{tot_words:,}** |")
    lines.append("")
    return "\n".join(lines)


def main():
    args = [a for a in sys.argv[1:] if not a.startswith("--")]
    out = None
    for a in sys.argv[1:]:
        if a.startswith("--out"):
            out = a.split("=", 1)[1] if "=" in a else "DATASET_STATS.md"
    files = args or discover()
    rows = []
    for path in files:
        try:
            rows.append(summarise(path))
        except Exception as e:  # noqa: BLE001
            print(f"skip {path}: {e}", file=sys.stderr)
    report = render(rows)
    print(report)
    if out:
        with open(out, "w") as f:
            f.write(report)
        print(f"\nWrote {out}", file=sys.stderr)


if __name__ == "__main__":
    main()
